import path from "path";
import fs from "fs/promises";

/**
 * All runtime data lives under ./data/ (gitignored). No database.
 *
 * SWIND_R_DATA_DIR redirects it elsewhere, which the test suite uses so unit
 * tests never touch real briefs or the shared Tavily cache.
 */
export const DATA_DIR = process.env.SWIND_R_DATA_DIR
  ? path.resolve(process.env.SWIND_R_DATA_DIR)
  : path.join(process.cwd(), "data");
export const BRIEFS_DIR = path.join(DATA_DIR, "briefs");
export const IMAGES_DIR = path.join(DATA_DIR, "images");
export const TAVILY_CACHE_DIR = path.join(DATA_DIR, "cache", "tavily");
export const USAGE_FILE = path.join(DATA_DIR, "usage.json");

export async function ensureDir(dir: string): Promise<void> {
  await fs.mkdir(dir, { recursive: true });
}

export async function ensureDataDirs(): Promise<void> {
  await ensureDir(BRIEFS_DIR);
  await ensureDir(IMAGES_DIR);
  await ensureDir(TAVILY_CACHE_DIR);
}

export function briefFile(id: string): string {
  return path.join(BRIEFS_DIR, `${id}.json`);
}

export function briefImagesDir(id: string): string {
  return path.join(IMAGES_DIR, id);
}

/** Screenshots are stored per domain so re-runs overwrite cleanly. */
export function screenshotFile(briefId: string, domain: string): string {
  const safe = domain.replace(/[^a-z0-9.-]/gi, "_");
  return path.join(briefImagesDir(briefId), `${safe}.jpg`);
}

/**
 * Guards against path traversal: brief ids are generated by us, but this
 * guards the dynamic routes against hand-typed ids.
 */
export function isSafeId(id: string): boolean {
  return /^[A-Za-z0-9_-]{1,64}$/.test(id);
}

/**
 * Reads and writes are serialized per file path. One brief runs at a time
 * (server-side lock), but the UI polls for status while the pipeline writes,
 * so writes must not interleave.
 */
const writeLocks = new Map<string, Promise<unknown>>();

export function withWriteLock<T>(key: string, fn: () => Promise<T>): Promise<T> {
  const previous = writeLocks.get(key) ?? Promise.resolve();
  const next = previous.then(fn, fn);
  writeLocks.set(
    key,
    next.catch(() => undefined),
  );
  return next;
}
